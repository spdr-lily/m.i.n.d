"""
⚠️  WARNING: ALL CLINICAL DATA GENERATED BY THIS SCRIPT IS SYNTHETIC.
⚠️  No real patient data is used. For development/testing/ML only.

Adiciona consultas recentes (datas até hoje) para uma amostra de pacientes,
reutilizando a lógica de geração de sintomas, escalas e inferências de
scripts/seed_clinical_data.py. Idempotente: não duplica consultas que já
possuem data no período recente.
"""

import importlib.util
import random
import sys
from datetime import datetime, timedelta
from uuid import uuid4

from sqlalchemy import create_engine, text
from sqlalchemy.orm import Session

from app.core.config import settings
from app.models.base import Base, PatientProfile, PatientIdentity, HealthcareProfessional
from app.models.base import (
    Symptom, Disorder, AssessmentScale, ScaleQuestion,
    ClinicalConsultation, SymptomObservation, DiagnosticInference,
    ProfessionalPatientAssignment,
)

# Load seed_clinical_data module so we can reuse its constants and helpers
spec = importlib.util.spec_from_file_location(
    "seed_clinical_data", "scripts/seed_clinical_data.py"
)
scd = importlib.util.module_from_spec(spec)
sys.modules["seed_clinical_data"] = scd
spec.loader.exec_module(scd)

random.seed(42)

# How many patients receive a recent consultation
TARGET_PATIENTS = 15

# Recent dates up to 13/08/2026 (today)
RECENT_DATES = [
    datetime(2026, 8, 10, 10, 30),
    datetime(2026, 8, 10, 14, 0),
    datetime(2026, 8, 11, 9, 15),
    datetime(2026, 8, 11, 16, 45),
    datetime(2026, 8, 12, 11, 0),
    datetime(2026, 8, 12, 15, 30),
    datetime(2026, 8, 13, 8, 45),
    datetime(2026, 8, 13, 13, 20),
]


def build_maps(session):
    """Rebuild symptom/disorder/scale maps the same way seed_clinical_data does."""
    symptom_map = {}
    for dd in scd.DISORDER_DEFS:
        for sname, sdesc, *_ in dd["symptoms"]:
            if sname in symptom_map:
                continue
            pt_name = scd.EN_TO_PT_SYMPTOM.get(sname, sname)
            existing = session.query(Symptom).filter_by(symptom_name=pt_name).first()
            if existing:
                symptom_map[sname] = existing.symptom_id

    disorder_map = {}
    for dd in scd.DISORDER_DEFS:
        existing = session.query(Disorder).filter_by(disorder_name=dd["name"]).first()
        if existing:
            disorder_map[dd["name"]] = existing.disorder_id

    scale_map = {}
    for sname, sdef in scd.SCALE_DEFS.items():
        existing_scale = session.query(AssessmentScale).filter_by(scale_name=sname).first()
        if existing_scale:
            questions = (
                session.query(ScaleQuestion)
                .filter_by(scale_id=existing_scale.scale_id)
                .order_by(ScaleQuestion.question_order)
                .all()
            )
            scale_map[sname] = {"scale": existing_scale, "questions": questions, "def": sdef}
    return symptom_map, disorder_map, scale_map


def patient_disorders_from_inferences(session, patient_uuid):
    """Derive a patient's disorder profile from their inference history.

    Returns the top 2 disorder names by max probability across consultations,
    falling back to a random DISORDER_DEFS pick when there is no history.
    """
    disorder_names = [dd["name"] for dd in scd.DISORDER_DEFS]
    rows = session.execute(text("""
        SELECT d.disorder_name, MAX(di.inference_probability) AS max_prob
        FROM diagnostic.diagnostic_inference di
        JOIN clinical.clinical_consultation c ON c.consultation_uuid = di.consultation_uuid
        JOIN diagnostic.disorders d ON d.disorder_id = di.disorder_id
        WHERE c.profile_uuid IN (SELECT profile_uuid FROM clinical.patient_profile WHERE patient_uuid = :pu)
        GROUP BY d.disorder_name
        ORDER BY max_prob DESC
    """), {"pu": patient_uuid}).fetchall()

    names = [r[0] for r in rows if r[0] in disorder_names]
    if not names:
        return [random.choice(disorder_names)]
    return names[:2]


def add_recent_consultations():
    engine = create_engine(settings.database_url, echo=False)
    Base.metadata.create_all(bind=engine)
    session = Session(bind=engine)

    symptom_map, disorder_map, scale_map = build_maps(session)

    patients = session.query(PatientProfile).order_by(PatientProfile.profile_uuid).all()
    if not patients:
        print("Nenhum paciente encontrado. Rode scripts/seed_clinical_data.py primeiro.")
        session.close()
        return

    professionals = session.query(HealthcareProfessional).all()
    if not professionals:
        print("Nenhum profissional encontrado.")
        session.close()
        return

    # Skip patients who already have a consultation on/after the earliest recent date
    earliest = RECENT_DATES[0]
    candidates = []
    for pp in patients:
        latest = (
            session.query(ClinicalConsultation)
            .filter_by(profile_uuid=pp.profile_uuid)
            .order_by(ClinicalConsultation.consultation_date.desc())
            .first()
        )
        if latest is None or latest.consultation_date < earliest:
            candidates.append(pp)

    if not candidates:
        print("Todos os pacientes já possuem consultas no período recente. Nada a fazer.")
        session.close()
        return

    sample = candidates[:TARGET_PATIENTS]
    print(f"Adicionando consultas recentes para {len(sample)} pacientes (de {len(candidates)} elegíveis)...")

    added = 0
    for i, pp in enumerate(sample):
        consult_date = RECENT_DATES[i % len(RECENT_DATES)]
        # Ensure no duplicate date for the same patient
        dup = (
            session.query(ClinicalConsultation)
            .filter_by(profile_uuid=pp.profile_uuid)
            .filter(ClinicalConsultation.consultation_date == consult_date)
            .first()
        )
        if dup:
            consult_date = consult_date + timedelta(hours=1)

        identity = session.query(PatientIdentity).filter_by(patient_uuid=pp.patient_uuid).first()
        patient_name = identity.full_name if identity else str(pp.patient_uuid)

        # Primary professional: the patient's active assignment
        assign = (
            session.query(ProfessionalPatientAssignment)
            .filter_by(patient_uuid=pp.patient_uuid, is_active=True)
            .first()
        )
        prof = (
            session.query(HealthcareProfessional)
            .filter_by(professional_uuid=assign.professional_uuid)
            .first()
            if assign
            else None
        )
        prof = prof or professionals[i % len(professionals)]

        consult = ClinicalConsultation(
            consultation_uuid=uuid4(),
            profile_uuid=pp.profile_uuid,
            professional_uuid=prof.professional_uuid,
            consultation_date=consult_date,
            consultation_notes=f"Consulta de acompanhamento recente — {consult_date.strftime('%d/%m/%Y')}",
        )
        session.add(consult)
        session.flush()

        disorders = patient_disorders_from_inferences(session, pp.patient_uuid)

        # Add symptoms for the patient's disorders (same sampling as _create_patients)
        for dd in scd.DISORDER_DEFS:
            if dd["name"] in disorders:
                for sname, sdesc, p_given, p_not, required, min_dur in dd["symptoms"]:
                    if random.random() < p_given * 0.85:
                        intensity = round(random.uniform(3.0, 9.0), 2)
                        freq_options = ["daily", "several_times_week", "weekly", "several_times_month"]
                        freq = random.choice(freq_options)
                        duration = random.randint(min_dur if min_dur > 0 else 1, max(min_dur + 60, 90))
                        session.add(SymptomObservation(
                            consultation_uuid=consult.consultation_uuid,
                            symptom_id=symptom_map[sname],
                            intensity=intensity,
                            frequency=freq,
                            duration_days=duration,
                            clinical_notes=sdesc,
                        ))

        scd._generate_scale_responses(session, consult, disorders, scale_map, symptom_map, disorder_map)
        added += 1
        print(f"  + {patient_name} ({pp.patient_uuid}) — {consult_date.strftime('%d/%m/%Y %H:%M')} — {', '.join(disorders)}")

    session.commit()

    total = session.query(ClinicalConsultation).count()
    latest = session.query(ClinicalConsultation).order_by(ClinicalConsultation.consultation_date.desc()).first()
    print(f"\nOK - {added} consultas recentes adicionadas. Total de consultas: {total}.")
    if latest:
        print(f"Última consulta: {latest.consultation_date}")
    session.close()


if __name__ == "__main__":
    add_recent_consultations()
