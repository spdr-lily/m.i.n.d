"""
⚠️  WARNING: ALL CLINICAL DATA GENERATED BY THIS SCRIPT IS SYNTHETIC.

Fill the gaps in August and September 2026 with distributed consultations.
Current distribution is very uneven — this adds ~1-2 per patient on dates
that have few/no consultations, producing a smoother graph.
"""

import importlib.util
import random
import sys
from datetime import date, datetime, time, timedelta
from uuid import uuid4

from sqlalchemy import create_engine, text
from sqlalchemy.orm import Session

from app.core.config import settings
from app.models.base import (
    Base, PatientProfile, HealthcareProfessional,
    Symptom, Disorder, AssessmentScale, ScaleQuestion,
    ClinicalConsultation, SymptomObservation,
    ProfessionalPatientAssignment,
)

spec = importlib.util.spec_from_file_location(
    "seed_clinical_data", "scripts/seed_clinical_data.py"
)
scd = importlib.util.module_from_spec(spec)
sys.modules["seed_clinical_data"] = scd
spec.loader.exec_module(scd)

spec2 = importlib.util.spec_from_file_location(
    "add_periodic", "scripts/add_periodic_consultations.py"
)
ap = importlib.util.module_from_spec(spec2)
sys.modules["add_periodic"] = ap
spec2.loader.exec_module(ap)

random.seed(77)

TOLERANCE_DAYS = 3


def fill_gaps():
    engine = create_engine(settings.database_url, echo=False)
    Base.metadata.create_all(bind=engine)
    session = Session(bind=engine)

    symptom_map, disorder_map, scale_map = ap.build_maps(session)

    patients = session.query(PatientProfile).order_by(PatientProfile.profile_uuid).all()
    professionals = session.query(HealthcareProfessional).all()

    # Count existing consultations per date
    date_counts = {}
    for r in session.execute(text(
        "SELECT consultation_date::date AS d, COUNT(*) AS cnt "
        "FROM clinical.clinical_consultation "
        "WHERE consultation_date >= '2026-08-01' AND consultation_date <= '2026-09-30' "
        "GROUP BY d"
    )).fetchall():
        date_counts[str(r[0])] = r[1]

    # Build candidate dates: Aug 14-27, Sep 1-13, Sep 17-28
    candidate_dates = []
    for d in range(14, 28):  # Aug 14-27
        candidate_dates.append(date(2026, 8, d))
    for d in range(1, 14):  # Sep 1-13
        candidate_dates.append(date(2026, 9, d))
    for d in range(17, 29):  # Sep 17-28
        candidate_dates.append(date(2026, 9, d))

    # Sort by how sparse they are (fewest existing consults first)
    candidate_dates.sort(key=lambda d: date_counts.get(str(d), 0))

    existing_by_profile = {}
    for c in session.query(ClinicalConsultation).all():
        existing_by_profile.setdefault(c.profile_uuid, set()).add(c.consultation_date.date())

    total_before = session.query(ClinicalConsultation).count()
    print(f"Total antes: {total_before}")
    print(f"Candidatos a preencher: {len(candidate_dates)} datas")
    print(f"Menos consultadas:")
    for d in candidate_dates[:5]:
        print(f"  {d}: {date_counts.get(str(d), 0)}")

    added = 0
    reused = 0
    month_counts = {8: 0, 9: 0}

    # For each patient, pick 2-4 dates from the sparse candidates
    for i, pp in enumerate(patients):
        disorders = ap.patient_disorders_from_inferences(session, pp.patient_uuid)

        assign = (
            session.query(ProfessionalPatientAssignment)
            .filter_by(patient_uuid=pp.patient_uuid, is_active=True)
            .first()
        )
        prof = (
            session.query(HealthcareProfessional)
            .filter_by(professional_uuid=assign.professional_uuid)
            .first()
            if assign
            else None
        )
        prof = prof or professionals[i % len(professionals)]

        existing_dates = existing_by_profile.get(pp.profile_uuid, set())

        # Pick 2-4 dates spread across the gap periods
        num = random.randint(2, 4)
        chosen = random.sample(candidate_dates, min(num, len(candidate_dates)))

        for consult_date in chosen:
            if any(abs((consult_date - ed).days) <= TOLERANCE_DAYS for ed in existing_dates):
                reused += 1
                continue

            hh = random.randint(8, 18)
            mm = random.choice([0, 15, 30, 45])
            consult_dt = datetime.combine(consult_date, time(hh, mm))

            consult = ClinicalConsultation(
                consultation_uuid=uuid4(),
                profile_uuid=pp.profile_uuid,
                professional_uuid=prof.professional_uuid,
                consultation_date=consult_dt,
                consultation_notes=(
                    f"Consulta de acompanhamento periódica — "
                    f"{consult_date.strftime('%d/%m/%Y')}"
                ),
            )
            session.add(consult)
            session.flush()

            for dd in scd.DISORDER_DEFS:
                if dd["name"] in disorders:
                    for sname, sdesc, p_given, p_not, required, min_dur in dd["symptoms"]:
                        if random.random() < p_given * 0.85:
                            intensity = round(random.uniform(3.0, 9.0), 2)
                            freq = random.choice(["daily", "several_times_week", "weekly", "several_times_month"])
                            duration = random.randint(min_dur if min_dur > 0 else 1, max(min_dur + 60, 90))
                            session.add(SymptomObservation(
                                consultation_uuid=consult.consultation_uuid,
                                symptom_id=symptom_map[sname],
                                intensity=intensity,
                                frequency=freq,
                                duration_days=duration,
                                clinical_notes=sdesc,
                            ))

            scd._generate_scale_responses(
                session, consult, disorders, scale_map, symptom_map, disorder_map
            )
            existing_dates.add(consult_date)
            month_counts[consult_date.month] += 1
            added += 1

    session.commit()

    new_total = session.query(ClinicalConsultation).count()
    print(f"\nOK - {added} consultas adicionadas ({reused} ignoradas por proximidade).")
    print(f"  Ago: {month_counts[8]}, Set: {month_counts[9]}")
    print(f"Total agora: {new_total} (antes {total_before})")

    # Show updated distribution
    print("\nDistribuição diária atualizada (Ago-Set):")
    rows = session.execute(text(
        "SELECT to_char(consultation_date, 'YYYY-MM-DD') AS day, COUNT(*) "
        "FROM clinical.clinical_consultation "
        "WHERE consultation_date >= '2026-08-01' "
        "GROUP BY day ORDER BY day"
    )).fetchall()
    for r in rows:
        print(f"  {r[0]}: {r[1]}")

    session.close()


if __name__ == "__main__":
    fill_gaps()
